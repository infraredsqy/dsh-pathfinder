#!/usr/bin/env node
/* Regenerate mock/ledger.js from a real .pf ledger.
 *
 * The mock exists to be judged against the content the panel will really hold,
 * and hand-copied titles drift. So the node pool, the five cycles, the five
 * walked paths and the standing instructions are read straight out of
 * ideas.json + state.json + instructions.json and written out as one data blob;
 * nothing here names a node, rewords a sentence or invents a timestamp.
 *
 *   node   id, title, tags, mode, created_at, completed_at, dependencies
 *   cycle  id, title, tags, status, created_at, updated_at,
 *          path[] = the steps that RAN (node, started_at, ended_at, result)
 *   instruction
 *          id, text (the user's own words, verbatim), scope, target, state,
 *          cycle binding, node binding, at, resolved_at, note, stop_after_nodes
 *
 * Only the -i frontier in data.js is invented, because a ledger with everything
 * completed has no todo node to copy and therefore nothing to draw a queue from.
 *
 *   node tools/gen-ledger.mjs [--ledger <path to .pf>]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '..', 'mock', 'ledger.js');

const argv = process.argv.slice(2);
const at = argv.indexOf('--ledger');
const LEDGER =
  at >= 0
    ? argv[at + 1]
: path.join(HERE, '..', '..', '.pf');

const ideas = JSON.parse(fs.readFileSync(path.join(LEDGER, 'ideas.json'), 'utf8'));
const state = JSON.parse(fs.readFileSync(path.join(LEDGER, 'state.json'), 'utf8'));

// The standing instructions: the user's own sentences, kept in the order they
// were said. `note` is the half a reader can act on -- for a closed entry it is
// why it stopped counting -- and `stop_after_nodes` is the one machine field
// (how many nodes to run before stopping).
const instrPath = path.join(LEDGER, 'instructions.json');
const instructions = (fs.existsSync(instrPath)
  ? JSON.parse(fs.readFileSync(instrPath, 'utf8')).instructions || []
  : []
).map((i) => [
  i.id,
  i.text || '',
  i.scope || 'global',
  i.target || 'stage',
  i.state || 'live',
  i.cycle === undefined ? null : i.cycle,
  i.node === undefined ? null : i.node,
  i.at || null,
  i.resolved_at || null,
  i.note || null,
  i.stop_after_nodes === undefined ? null : i.stop_after_nodes
]);

const raw = ideas.nodes;
const nodes = Object.keys(raw).map((id) => {
  const n = raw[id];
  return [
    id,
    n.title || '',
    n.tags || [],
    n.mode || 'auto',
    n.created_at || null,
    n.completed_at || null,
    n.dependencies || []
  ];
});
// Chronological, oldest completion first: the grid of a census reads as the
// order the project was built, and an unfinished node sorts to the end.
nodes.sort((a, b) => String(a[5] || '9999').localeCompare(String(b[5] || '9999')));

const cycles = state.cycles.map((c) => ({
  id: c.id,
  title: c.title || '',
  status: c.status || 'inactive',
  tags: c.tags || [],
  created: c.created_at || null,
  updated: c.updated_at || null,
  policies: c.policies || {},
  // Old-format ledgers also carry current_node / current_started_at, singletons
  // that the tool has since generalised to a holding list. Both are read so the
  // generator works against either shape.
  holding:
    c.holding ||
    (c.current_node ? [{ id: c.current_node, since: c.current_started_at || null }] : []),
  path: (c.path || []).map((p) => [p.node, p.started_at || null, p.ended_at || null, p.result || null])
}));

// ---- what the source actually contains, so a drift shows up as a number ----
const inPaths = new Set();
cycles.forEach((c) => c.path.forEach((p) => inPaths.add(p[0])));
const missing = nodes.map((n) => n[0]).filter((id) => !inPaths.has(id));
const orphan = [...inPaths].filter((id) => !raw[id]);
const withDeps = nodes.filter((n) => n[6].length).length;
const stamps = nodes.map((n) => n[5]).filter(Boolean).sort();

const body = [];
body.push('/* GENERATED by tools/gen-ledger.mjs -- do not edit by hand.');
body.push(' *');
body.push(' * Verbatim from a real .pf ledger: the node pool, the five cycles, the');
body.push(' * steps each cycle actually walked, and the standing instructions. Nothing');
body.push(' * in this file is invented, and no timestamp is adjusted; the only fiction in');
body.push(' * the mock lives in data.js.');
body.push(' *');
body.push(` *   source   ${LEDGER}`);
body.push(` *   nodes    ${nodes.length}`);
body.push(` *   cycles   ${cycles.length}`);
body.push(` *   steps    ${cycles.reduce((s, c) => s + c.path.length, 0)}`);
body.push(` *   instructions ${instructions.length}`);
body.push(' *');
body.push(' * nodes[i] = [id, title, tags, mode, created_at, completed_at, dependencies]');
body.push(' * cycle.path[j] = [node, started_at, ended_at, result]');
body.push(' * instructions[k] = [id, text, scope, target, state, cycle, node, at,');
body.push(' *                     resolved_at, note, stop_after_nodes]');
body.push(' */');
body.push('window.PF_LEDGER = {');
body.push(`  source: ${JSON.stringify(LEDGER)},`);
body.push('  nodes: [');
nodes.forEach((n) => {
  const row = n.map((v) => JSON.stringify(v)).join(',');
  body.push(`    [${row}],`);
});
body.push('  ],');
body.push('  cycles: [');
cycles.forEach((c) => {
  body.push('    {');
  body.push(`      id: ${JSON.stringify(c.id)},`);
  body.push(`      title: ${JSON.stringify(c.title)},`);
  body.push(`      status: ${JSON.stringify(c.status)},`);
  body.push(`      tags: ${JSON.stringify(c.tags)},`);
  body.push(`      created: ${JSON.stringify(c.created)},`);
  body.push(`      updated: ${JSON.stringify(c.updated)},`);
  body.push(`      policies: ${JSON.stringify(c.policies)},`);
  body.push(`      holding: ${JSON.stringify(c.holding)},`);
  body.push('      path: [');
  c.path.forEach((p) => {
    body.push(`        [${p.map((v) => JSON.stringify(v)).join(',')}],`);
  });
  body.push('      ]');
  body.push('    },');
});
body.push('  ],');
body.push('  instructions: [');
instructions.forEach((r) => {
  body.push(`    [${r.map((v) => JSON.stringify(v)).join(',')}],`);
});
body.push('  ]');
body.push('};');
body.push('');

fs.writeFileSync(OUT, body.join('\n'), 'utf8');

console.log(`wrote ${OUT} (${fs.statSync(OUT).size} bytes)`);
console.log(`nodes ${nodes.length}  cycles ${cycles.length}  steps ${cycles.reduce((s, c) => s + c.path.length, 0)}`);
cycles.forEach((c) =>
  console.log(
    `  ${c.id.padEnd(14)} path=${String(c.path.length).padStart(3)}  ` +
      `results=${JSON.stringify(
        c.path.reduce((m, p) => ((m[p[3]] = (m[p[3]] || 0) + 1), m), {})
      )}  holding=${c.holding.length}  tags=${JSON.stringify(c.tags)}`
  )
);
console.log(`nodes carrying dependencies: ${withDeps}`);
console.log(`path nodes not in the pool: ${JSON.stringify(orphan)}`);
console.log(`pool nodes never walked: ${missing.length}${missing.length ? ' ' + JSON.stringify(missing.slice(0, 4)) : ''}`);
console.log(`completed_at span ${stamps[0]} .. ${stamps[stamps.length - 1]}`);
const tally = (key) => instructions.reduce((m, r) => ((m[r[key]] = (m[r[key]] || 0) + 1), m), {});
console.log(
  `instructions ${instructions.length}  scope=${JSON.stringify(tally(2))}  ` +
    `state=${JSON.stringify(tally(4))}  target=${JSON.stringify(tally(3))}`
);
const bound = instructions.filter((r) => r[2] === 'cycle' && !r[5]).length;
console.log(`  cycle entries with no cycle binding: ${bound}`);