import { cpSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, describe, expect, it } from 'vitest';
import { prepareDispatch } from '../src/prepare';
import { open } from '../src/open';
import { generateExpected, type CorpusRunner } from './helpers/corpus';
import { makeLab } from './helpers/plugin-lab';
import { hashDirectory } from './helpers/hash-dir.ts';

/**
 * Dispatch preparation (the first half of `conductor.dispatch`): the run doc, the prompt and the
 * handoff template.
 *
 * The corpus (tests/fixtures/dispatch-*) pins the **bytes** of the material and of the landing
 * spots — the one line of the prompt, the checked facts of the run doc, repeated preparation and
 * "no file lands outside the node directory"; once the verb is wired in, those cases join the list
 * in tests/corpus.test.ts and are replayed from the public handle (`conductor.dispatch` itself),
 * and what stays here are the faces the corpus cannot reach: a byte snapshot of the template and
 * the prompt, idempotence (a third pass moves not a byte, a run doc the session wrote is not
 * overwritten), and the "only plans that dispatch" gate. The generation-side round trip still goes
 * through the `prepareDispatch` runner (that side only lays down these two text products, the same
 * byte set as the committed expected/).
 */

const fixturesDir = fileURLToPath(new URL('./fixtures', import.meta.url));
const roots: string[] = [];

function freshRoot(): string {
  const root = mkdtempSync(join(tmpdir(), 'pf-prepare-'));
  roots.push(root);
  return root;
}

afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

function toLf(text: string): string {
  return text.replace(/\r\n/g, '\n');
}

/**
 * Corpus replay uses the same runner: preparation closes home into the temporary project root, so
 * readings do not depend on the real machine.
 */
const runner: CorpusRunner = (root, args) =>
  prepareDispatch(root, (args[0] ?? {}) as { cycle?: string }, { homeDir: join(root, '_home') });

/** Stage a scene that can be dispatched: init → one active cycle → one pinned node. */
async function stageDispatchable(root: string): Promise<{ pf: ReturnType<typeof open>; node: { id: string } }> {
  const pf = open(root);
  await pf.ledger.init();
  const node = await pf.ledger.dag.add({ title: 'prepare the round' });
  await pf.ledger.cycles.create({ id: 'c1', tags: ['writing'] });
  await pf.ledger.cycles.hold('c1', node.id);
  return { pf, node };
}

/** The file list relative to the project root (forward slashes, sorted). */
function walkRel(root: string): string[] {
  const out: string[] = [];
  const walk = (current: string, prefix: string) => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const rel = prefix === '' ? entry.name : `${prefix}/${entry.name}`;
      if (statSync(join(current, entry.name)).isDirectory()) walk(join(current, entry.name), rel);
      else out.push(rel);
    }
  };
  walk(root, '');
  return out.sort();
}

describe('dispatch preparation: the generation side round-trips the committed bytes', () => {
  it('generation-side round trip: rerunning the generation side on a copy of dispatch-basic yields the same bytes as the committed expected/', async () => {
    const copy = mkdtempSync(join(tmpdir(), 'pf-prepare-gen-'));
    roots.push(copy);
    cpSync(join(fixturesDir, 'dispatch-basic'), join(copy, 'dispatch-basic'), { recursive: true });
    const caseCopy = join(copy, 'dispatch-basic');
    const written = (await generateExpected(caseCopy, runner)).sort();
    const committedDir = join(fixturesDir, 'dispatch-basic', 'expected');
    const committed = walkRel(committedDir);
    expect(written, 'the file list the generation side wrote differs from the committed expected/').toEqual(committed);
    // The byte lock folds to LF before the byte compare, as the fixture convention says: autocrlf on
    // the checkout side turns text fixtures into CRLF, and folding the EOL difference still locks
    // every content byte (the same convention as the replayer's text products).
    const toLf = (text: string): string => text.split('\r\n').join('\n');
    for (const rel of committed) {
      const regenerated = readFileSync(join(caseCopy, 'expected', ...rel.split('/')), 'utf8');
      const golden = readFileSync(join(committedDir, ...rel.split('/')), 'utf8');
      expect(
        toLf(regenerated) === toLf(golden),
        `${rel}: the regenerated bytes differ from the committed ones`,
      ).toBe(true);
    }
  });
});

describe('dispatch preparation: prompt and handoff template', () => {
  it('the prompt is one line: nothing beyond the invocation, matching the bytes written to disk', async () => {
    const root = freshRoot();
    const { node } = await stageDispatchable(root);
    const prepared = await prepareDispatch(root, { cycle: 'c1' }, { homeDir: join(root, '_home') });
    expect(prepared.nodes).toHaveLength(1);
    expect(prepared.nodes[0]!.prompt_text).toBe(`/pf-conduct ${node.id} [pipeline]\n`);
    const onDisk = readFileSync(prepared.nodes[0]!.prompt, 'utf8');
    expect(toLf(onDisk)).toBe(prepared.nodes[0]!.prompt_text);
  });

  it('handoff template: a byte snapshot of the fields and of the shape of the verdict words', async () => {
    const root = freshRoot();
    const { node } = await stageDispatchable(root);
    const prepared = await prepareDispatch(root, { cycle: 'c1' }, { homeDir: join(root, '_home') });
    expect(prepared.nodes[0]!.handoff_template).toBe(
      `the ticket this line (c1) asks for (${node.id}):\n\n` +
        'status: completed | failed | stopped\n' +
        'summary: "<one-line summary>"\n' +
        'outputs: {"deliverable":"<path to the thing this node is meant to produce>",' +
        '"acceptance":["<key acceptance point 1>","<key acceptance point 2>"],' +
        '"touched":["<files you changed under this node>"]}\n',
    );
  });

  it('handoff template: a cycle with a configured reading gets one more cell, reading (it asks what the declaration asks; a cycle without one has no such cell)', async () => {
    const lab = makeLab('pf-prepare-reading-');
    roots.push(lab.root);
    await lab.pf.ledger.init();
    const nodeId = (await lab.pf.ledger.dag.add({ title: 'audited slot' })).id;
    lab.cycle('c1', [nodeId]);
    // One plugin declares a source: ticket reading whose when_knob defaults to in force on a fresh
    // install; the other's gate is unconfigured, so it is not asked.
    lab.plugin('audit', {
      name: 'audit',
      summary: 'asks the worker for the measured seconds',
      knobs: { audit_min_seconds: { kind: 'number', default: 30, summary: 'the floor the close judges with' } },
      readings: {
        test_seconds: { source: 'ticket', ask: 'how many seconds the full suite ran', when_knob: 'audit_min_seconds' },
      },
    }, {});
    lab.plugin('muted', {
      name: 'muted',
      summary: 'a reading whose gate nobody configured',
      knobs: { muted_min_seconds: { kind: 'number', default: null, summary: 'no default, no layer: not in force' } },
      readings: {
        muted_seconds: { source: 'ticket', ask: 'never asked', when_knob: 'muted_min_seconds' },
      },
    }, {});
    const prepared = await prepareDispatch(lab.root, { cycle: 'c1' }, { homeDir: lab.home });
    expect(prepared.nodes[0]!.handoff_template).toBe(
      `the ticket this line (c1) asks for (${nodeId}):\n\n` +
        'status: completed | failed | stopped\n' +
        'summary: "<one-line summary>"\n' +
        'outputs: {"deliverable":"<path to the thing this node is meant to produce>",' +
        '"acceptance":["<key acceptance point 1>","<key acceptance point 2>"],' +
        '"touched":["<files you changed under this node>"],' +
        '"reading":{"test_seconds":<how many seconds the full suite ran>}}\n',
    );
  });
});

describe('dispatch preparation: landing spots and idempotence', () => {
  it('there are only two products: the prompt lands in the dispatch folder, the run doc in the node directory', async () => {
    const root = freshRoot();
    const { node } = await stageDispatchable(root);
    const before = new Set(walkRel(root));
    const prepared = await prepareDispatch(root, { cycle: 'c1' }, { homeDir: join(root, '_home') });
    const added = walkRel(root).filter((rel) => !before.has(rel));
    expect(added.sort()).toEqual([
      `.pf/meta/launch/c1/${node.id}/prompt.txt`,
      `.pf/nodes/${node.id}/run.md`,
    ]);
    expect(prepared.nodes[0]!.run_doc).toBe(join(root, '.pf', 'nodes', node.id, 'run.md'));
  });

  it('human-read text products keep the platform line ending: the prompt and the run doc are not folded to LF', async () => {
    // The two-sided byte rule: machine-read records are LF on every platform, the text a person
    // opens follows the platform. Every other comparison folds the ending away, so this is the one
    // place that reads the products back as they lie on disk. On Windows a fold to LF shows up as a
    // lone `\n`; on a platform whose ending is LF the same fold is invisible, so the negative half
    // is the only assertion there.
    const root = freshRoot();
    await stageDispatchable(root);
    const prepared = await prepareDispatch(root, { cycle: 'c1' }, { homeDir: join(root, '_home') });
    const products = [prepared.nodes[0]!.prompt, prepared.nodes[0]!.run_doc];
    for (const path of products) {
      const text = readFileSync(path, 'utf8');
      expect(text.length, `${path} is empty`).toBeGreaterThan(0);
      if (process.platform === 'win32') {
        expect(text, `${path} carries no CRLF`).toContain('\r\n');
        expect(text.split('\r\n').join(''), `${path} carries a lone LF`).not.toContain('\n');
      } else {
        expect(text, `${path} carries a CRLF`).not.toContain('\r\n');
      }
    }
  });

  it('repeated preparation is idempotent: after a third pass the record tree has not moved a byte', async () => {
    const root = freshRoot();
    await stageDispatchable(root);
    await prepareDispatch(root, { cycle: 'c1' }, { homeDir: join(root, '_home') });
    const afterFirst = hashDirectory(join(root, '.pf'));
    await prepareDispatch(root, { cycle: 'c1' }, { homeDir: join(root, '_home') });
    await prepareDispatch(root, { cycle: 'c1' }, { homeDir: join(root, '_home') });
    expect(hashDirectory(join(root, '.pf'))).toBe(afterFirst);
  });

  it('a written run doc is left alone: what the session wrote into it is not overwritten by the next preparation', async () => {
    const root = freshRoot();
    const { node } = await stageDispatchable(root);
    await prepareDispatch(root, { cycle: 'c1' }, { homeDir: join(root, '_home') });
    const runDoc = join(root, '.pf', 'nodes', node.id, 'run.md');
    writeFileSync(runDoc, '## 做了什么\n\n写了东西。\n', 'utf8');
    await prepareDispatch(root, { cycle: 'c1' }, { homeDir: join(root, '_home') });
    expect(readFileSync(runDoc, 'utf8')).toContain('写了东西。');
    // The prompt is different: it is the "waiting to be picked up" marker, and every preparation
    // replaces the whole file with the same bytes.
    const prompt = join(root, '.pf', 'meta', 'launch', 'c1', node.id, 'prompt.txt');
    expect(existsSync(prompt)).toBe(true);
  });

  it('two preparations, one run doc: the bytes on disk are the first preparation\'s, and the second lands nothing of its own', async () => {
    const root = freshRoot();
    const { pf, node } = await stageDispatchable(root);
    const runDoc = join(root, '.pf', 'nodes', node.id, 'run.md');
    await prepareDispatch(root, { cycle: 'c1' }, { homeDir: join(root, '_home') });
    const first = readFileSync(runDoc, 'utf8');
    expect(first).toContain('# run.md — 节点');
    // The record moves on between the two preparations, so the second build really differs: if
    // the second preparation wrote, its bytes would show the new title.
    await pf.ledger.dag.update(node.id, { title: 'renamed while the session works' });
    await prepareDispatch(root, { cycle: 'c1' }, { homeDir: join(root, '_home') });
    expect(readFileSync(runDoc, 'utf8')).toBe(first);
    expect(readFileSync(runDoc, 'utf8')).not.toContain('renamed while the session works');
    // Exactly one run doc: the second preparation produced no second copy anywhere.
    const nodeDir = join(root, '.pf', 'nodes', node.id);
    expect(readdirSync(nodeDir).filter((name) => name.startsWith('run'))).toEqual(['run.md']);
  });

  it('the checked facts in the run doc come from record readings: mode, weight, cycle policy and settings', async () => {
    const root = freshRoot();
    const { pf, node } = await stageDispatchable(root);
    await pf.ledger.dag.update(node.id, { mode: 'checkpoint' });
    await pf.ledger.cycles.setPolicy('c1', 'parallel', 2);
    const prepared = await prepareDispatch(root, { cycle: 'c1' }, { homeDir: join(root, '_home') });
    const doc = readFileSync(prepared.nodes[0]!.run_doc, 'utf8');
    expect(doc).toContain('# run.md — 节点');
    expect(doc).toContain(`mode=checkpoint`);
    expect(doc).toContain('Policy: when_shelved=stop, parallel=2');
    expect(doc).toContain('- test_tier=full');
    expect(doc).toContain('- spec: ');
  });
});

describe('dispatch preparation: only plans that dispatch', () => {
  it('the cycle holds no node (planning answers open_node): there is no material to prepare, said on the spot', async () => {
    const root = freshRoot();
    const pf = open(root);
    await pf.ledger.init();
    await pf.ledger.dag.add({ title: 'not pinned yet' });
    await pf.ledger.cycles.create({ id: 'c1', tags: ['writing'] });
    await expect(
      prepareDispatch(root, { cycle: 'c1' }, { homeDir: join(root, '_home') }),
    ).rejects.toThrow(/open_node/);
  });

  it('the session is already open (planning answers wait): no second set of material is prepared', async () => {
    const root = freshRoot();
    const { node } = await stageDispatchable(root);
    const marker = join(root, '.pf', 'meta', 'launch', 'c1', node.id, 'started');
    mkdirSync(join(marker, '..'), { recursive: true });
    writeFileSync(marker, '4242 started 2026-01-01T00:00:00Z\n', 'utf8');
    await expect(
      prepareDispatch(root, { cycle: 'c1' }, { homeDir: join(root, '_home') }),
    ).rejects.toThrow(/wait/);
  });

  it('a named node that is not on the dispatch list: it says so on the spot instead of quietly dispatching another', async () => {
    const root = freshRoot();
    const pf = open(root);
    await pf.ledger.init();
    const a = await pf.ledger.dag.add({ title: 'slot a' });
    const b = await pf.ledger.dag.add({ title: 'slot b' });
    await pf.ledger.cycles.create({ id: 'c1', tags: ['writing'] });
    await pf.ledger.cycles.setPolicy('c1', 'parallel', 2);
    await pf.ledger.cycles.hold('c1', a.id);
    await pf.ledger.cycles.hold('c1', b.id);
    const marker = join(root, '.pf', 'meta', 'launch', 'c1', b.id, 'started');
    mkdirSync(join(marker, '..'), { recursive: true });
    writeFileSync(marker, '4242 started 2026-01-01T00:00:00Z\n', 'utf8');
    await expect(
      prepareDispatch(root, { cycle: 'c1', node: b.id }, { homeDir: join(root, '_home') }),
    ).rejects.toThrow(/not on the list/);
    // Name the one that is on the list: only that one gets prepared.
    const prepared = await prepareDispatch(
      root,
      { cycle: 'c1', node: a.id },
      { homeDir: join(root, '_home') },
    );
    expect(prepared.nodes.map((entry) => entry.node_id)).toEqual([a.id]);
  });
});
